-- Run in Studio with the two ModuleScripts next to this Script. No API access needed.
local RunService=game:GetService("RunService")
assert(RunService:IsStudio(),"Studio smoke test only")
local StateMachine=require(script.Parent.StateMachine)
local Group=require(script.Parent.StateMachineGroup)
local passed,failed=0,0
local function test(name,fn)
	local ok,err=pcall(fn)
	if ok then passed+=1; print("[StateMachine PASS] "..name)
	else failed+=1; warn("[StateMachine FAIL] "..name..": "..tostring(err)) end
end
local function eq(a,b) assert(rawequal(a,b),tostring(a).." ~= "..tostring(b)) end
local graph=StateMachine.compile({Initial="Ready",States={
	Ready={Transitions={Cooldown=function(c) return c.Allow end},Events={Use="Cooldown"}},
	Cooldown={Transitions={Ready=true},After={Seconds=2,Target="Ready"}},
}})
test("module version",function() eq(StateMachine.VERSION,"3.0.0-rc.2"); eq(Group.VERSION,"3.0.0-rc.2") end)
test("independent instances and guards",function()
	local a,b=graph:Create({Allow=true}),graph:Create({Allow=false})
	eq(a:Send("Use"),true); eq(b:Send("Use"),false); eq(b:GetState(),"Ready"); a:Destroy(); b:Destroy()
end)
test("timed transition",function()
	local m=graph:Create({Allow=true}); eq(m:Send("Use"),true); eq(m:Step(1),true); eq(m:GetRemaining(),1); eq(m:Step(1),true); eq(m:GetState(),"Ready"); m:Destroy()
end)
test("stale token after state ABA",function()
	local m=graph:Create({Allow=true}); local token=m:Token(); m:Send("Use"); m:Step(2)
	local ok,code=m:SendIfCurrent(token,"Use"); eq(ok,false); eq(code,"STALE_TOKEN"); m:Destroy()
end)
test("self transition explicitly resets time",function()
	local m=StateMachine.new({Initial="A",States={A={Transitions={A=true}}}}); local token=m:Token(); m:Step(1); eq(m:Transition("A"),true); eq(m:GetElapsed(),0); eq(m:IsCurrent(token),false); m:Destroy()
end)
test("guard error does not commit",function()
	local m=StateMachine.new({Initial="A",States={A={Transitions={B=function() error("expected") end}},B={}}})
	local ok,code=m:Transition("B"); eq(ok,false); eq(code,"CALLBACK_ERROR"); eq(m:GetState(),"A"); m:Destroy()
end)
test("task.wait in guard is cancelled",function()
	local resumed=false
	local m=StateMachine.new({Initial="A",States={A={Transitions={B=function() task.wait(0.02); resumed=true; return true end}},B={}}})
	local ok,code=m:Transition("B"); eq(ok,false); eq(code,"CALLBACK_YIELDED"); task.wait(0.12); eq(resumed,false); eq(m:GetState(),"A"); m:Destroy()
end)
test("notification error remains committed",function()
	local calls=0; local m=StateMachine.new({Initial="A",States={A={Transitions={B=true},Exit=function() error("expected") end},B={Enter=function() calls+=1 end}}})
	local ok,code,issues=m:Transition("B"); eq(ok,true); eq(code,"NOTIFICATION_FAILED"); eq(#issues,1); eq(calls,1); eq(m:GetState(),"B"); m:Destroy()
end)
test("task.wait in notification is cancelled",function()
	local resumed=false; local m=StateMachine.new({Initial="A",States={A={Transitions={B=true}},B={Enter=function() task.wait(0.02); resumed=true end}}})
	local ok,code,issues=m:Transition("B"); eq(ok,true); eq(code,"NOTIFICATION_FAILED"); eq(issues[1].Code,"CALLBACK_YIELDED"); task.wait(0.12); eq(resumed,false); eq(m:GetState(),"B"); m:Destroy()
end)
test("reentrant mutation rejected",function()
	local m; m=StateMachine.new({Initial="A",States={A={Transitions={B=function() local ok,e=m:Destroy(); eq(ok,false); eq(e,"BUSY"); return true end}},B={}}})
	eq(m:Transition("B"),true); m:Destroy()
end)
test("Heartbeat integration",function()
	local m=graph:Create({Allow=true}); m:Send("Use"); local n=0
	local conn=RunService.Heartbeat:Connect(function(dt) n+=1; m:Step(dt) end)
	task.wait(0.12); conn:Disconnect(); assert(n>0); assert(m:GetElapsed()>0); m:Destroy()
end)
test("group membership changes during Step",function()
	local g=Group.new(); local b={Step=function() error("must not run this tick") end}
	local added={Step=function() return true end}; local a={Step=function() g:Remove(b); g:Add(added); return true end}
	g:Add(a); g:Add(b); local ok,r=g:Step(0); eq(ok,true); eq(r.Attempted,1); eq(r.Failed,0); eq(g:Has(added),true); g:Destroy()
end)
test("group cancellation of yielding adapter",function()
	local resumed=false; local g=Group.new(); g:Add({Step=function() task.wait(0.02); resumed=true; return true end})
	local ok,r=g:Step(0); eq(ok,true); eq(r.Failed,1); eq(r.Issues[1].Code,"STEP_YIELDED"); task.wait(0.12); eq(resumed,false); g:Destroy()
end)
test("destroyed member removed but group is not owner",function()
	local g=Group.new(); local a,b=graph:Create({Allow=true}),graph:Create({Allow=true}); g:Add(a); g:Add(b); a:Destroy()
	local ok,r=g:Step(0); eq(ok,true); eq(r.RemovedDestroyed,1); eq(g:Count(),1); g:Destroy(); eq(b:GetState(),"Ready"); b:Destroy()
end)
test("zero dt preserves accumulated time",function()
	local m=graph:Create({Allow=true}); m:Step(0.000009); m:Step(0.00002); local before=m:GetElapsed(); m:Step(0); eq(m:GetElapsed(),before); m:Destroy()
end)
print(string.format("[StateMachine] RESULT: %d/%d PASS; %d FAIL",passed,passed+failed,failed))
